"""aclib — a tiny arithmetic-constraint DSL for Week 1 (pure Python, no deps).

This is the "common intermediate representation" idea from the lecture: a circuit
is just a set of polynomial constraints over a finite field F_p that must all
equal 0.  A *witness* is an assignment of a field element to every signal.

You (the student) do NOT edit this file.  You only import it:

    from aclib import ConstraintSystem

and build circuits with it.  See the problem README for the API you need.

Key idea for the assignment
---------------------------
A signal that you introduce is *free* unless a constraint pins it down.  The
grader plays a malicious prover: it will try to find ANY assignment that
satisfies your constraints while the credential is actually unauthorized.  If
such an assignment exists, your circuit is *under-constrained* (unsound).
"""

from __future__ import annotations

# BN254 scalar field prime (same field you will meet again with Circom later).
P = 21888242871839275222246405745257275088548364400416034343698204186575808495617


def _fe(x: int) -> int:
    return x % P


def _coerce(v: "Expr | int") -> "Expr":
    if isinstance(v, Expr):
        return v
    return Expr.constant(v)


class Expr:
    """A polynomial over F_p in the circuit's signals.

    Represented as {monomial: coeff}, where a monomial is a sorted tuple of
    signal ids (repeated ids encode powers), and () is the constant term.
    You never build this by hand — you get signals from the ConstraintSystem
    and combine them with +, -, * and Python ints.
    """

    __slots__ = ("terms",)

    def __init__(self, terms: dict[tuple[int, ...], int] | None = None) -> None:
        self.terms = terms or {}

    @staticmethod
    def constant(c: int) -> "Expr":
        c = _fe(c)
        return Expr({(): c}) if c else Expr({})

    @staticmethod
    def var(idx: int) -> "Expr":
        return Expr({(idx,): 1})

    def __add__(self, other: "Expr | int") -> "Expr":
        other = _coerce(other)
        out = dict(self.terms)
        for m, c in other.terms.items():
            out[m] = _fe(out.get(m, 0) + c)
        return Expr({m: c for m, c in out.items() if c})

    __radd__ = __add__

    def __neg__(self) -> "Expr":
        return Expr({m: _fe(-c) for m, c in self.terms.items()})

    def __sub__(self, other: "Expr | int") -> "Expr":
        return self + (-_coerce(other))

    def __rsub__(self, other: "Expr | int") -> "Expr":
        return _coerce(other) + (-self)

    def __mul__(self, other: "Expr | int") -> "Expr":
        other = _coerce(other)
        out: dict[tuple[int, ...], int] = {}
        for m1, c1 in self.terms.items():
            for m2, c2 in other.terms.items():
                m = tuple(sorted(m1 + m2))
                out[m] = _fe(out.get(m, 0) + c1 * c2)
        return Expr({m: c for m, c in out.items() if c})

    __rmul__ = __mul__

    def degree(self) -> int:
        return max((len(m) for m in self.terms), default=0)

    def signals(self) -> set[int]:
        return {idx for m in self.terms for idx in m}

    def evaluate(self, values: dict[int, int]) -> int:
        total = 0
        for m, c in self.terms.items():
            term = c
            for idx in m:
                term = _fe(term * values[idx])
            total = _fe(total + term)
        return total


class ConstraintSystem:
    """Collects signals and constraints.  The grader instantiates this for you.

    API you use inside build()/attack():
        cs.input(name, value)   -> a *credential* signal (role/clearance/region)
        cs.aux(name, value)     -> an internal helper signal you introduce
        cs.assert_zero(expr)    -> require expr == 0 over F_p
        cs.set_output(signal)   -> declare which signal is `granted`
    Every signal is created with a witness value (an int); constraints are added
    with assert_zero.  Constants and Python ints mix freely with signals.
    """

    def __init__(self) -> None:
        self.idx2name: list[str] = []
        self.name2idx: dict[str, int] = {}
        self.values: dict[int, int] = {}
        self.role: dict[int, str] = {}          # idx -> "input" | "aux"
        self.constraints: list[Expr] = []
        self.output_idx: int | None = None

    def _new_signal(self, name: str, value: int, role: str) -> Expr:
        if name in self.name2idx:
            raise ValueError(f"signal {name!r} already declared")
        idx = len(self.idx2name)
        self.idx2name.append(name)
        self.name2idx[name] = idx
        self.values[idx] = _fe(value)
        self.role[idx] = role
        return Expr.var(idx)

    def input(self, name: str, value: int) -> Expr:
        """Declare a credential signal (part of what is being proven)."""
        return self._new_signal(name, value, "input")

    def aux(self, name: str, value: int) -> Expr:
        """Declare an internal helper signal (flags, selectors, ...)."""
        return self._new_signal(name, value, "aux")

    def assert_zero(self, expr: "Expr | int") -> None:
        self.constraints.append(_coerce(expr))

    def set_output(self, signal: "Expr") -> None:
        sig = _coerce(signal)
        if len(sig.terms) != 1 or sig.degree() != 1 or list(sig.terms.values())[0] != 1:
            raise ValueError("set_output expects a single signal (e.g. `granted`)")
        self.output_idx = next(iter(sig.terms))[0]

    # ---- helpers used by the grader (you don't need these) ----
    def satisfied_by(self, assignment: dict[str, int]) -> bool:
        values = self._resolve(assignment)
        return all(c.evaluate(values) == 0 for c in self.constraints)

    def first_unsatisfied(self, assignment: dict[str, int]):
        values = self._resolve(assignment)
        for i, c in enumerate(self.constraints):
            if c.evaluate(values) != 0:
                return i
        return None

    def _resolve(self, assignment: dict[str, int]) -> dict[int, int]:
        values: dict[int, int] = {}
        for name, idx in self.name2idx.items():
            if name not in assignment:
                raise KeyError(f"assignment is missing signal {name!r}")
            values[idx] = _fe(assignment[name])
        return values
