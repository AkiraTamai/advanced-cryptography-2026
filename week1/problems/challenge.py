"""challenge.py — the circuit you must BREAK in Part B.

This is a small access-control circuit.  It is supposed to enforce:

    granted == 1   <=>   role in ROLE_OK  AND  clearance in CLEARANCE_OK
                                          AND  region in REGION_OK

It uses the standard "membership flag" trick for each field:

    f is a boolean, and   f * prod_{a in ALLOW}(x - a) == 0
    so   f == 1  forces  x in ALLOW.

...except that this particular deployment shipped with a bug.  Exactly one of
the three fields is NOT actually pinned to its allowlist.  Your job in Part B is
to hand in a witness (an assignment to every signal) that:

  * satisfies every constraint in this circuit, and
  * has granted == 1, and
  * uses a credential that is NOT authorized under spec.authorized().

You do not edit this file.  Read it, find the missing constraint, and construct
the exploiting witness in your solution.py `attack()` function.  The helper
`honest_witness(role, clearance, region)` gives you the honest assignment as a
starting point — you then tamper with it.
"""

from __future__ import annotations

from spec import ROLE_OK, CLEARANCE_OK, REGION_OK, authorized


def _membership_product(x, allowlist):
    """prod_{a in allowlist} (x - a)  — zero iff x equals some a in the list."""
    out = x - allowlist[0]
    for a in allowlist[1:]:
        out = out * (x - a)
    return out


def build(cs, role: int, clearance: int, region: int):
    """Declare the (buggy) circuit.  Returns the `granted` signal."""
    r = cs.input("role", role)
    c = cs.input("clearance", clearance)
    g = cs.input("region", region)

    f_role = cs.aux("f_role", 1 if role in ROLE_OK else 0)
    f_clear = cs.aux("f_clearance", 1 if clearance in CLEARANCE_OK else 0)
    f_region = cs.aux("f_region", 1 if region in REGION_OK else 0)
    granted = cs.aux("granted", 1 if authorized(role, clearance, region) else 0)

    # Each flag must be a bit.
    cs.assert_zero(f_role * f_role - f_role)
    cs.assert_zero(f_clear * f_clear - f_clear)
    cs.assert_zero(f_region * f_region - f_region)
    cs.assert_zero(granted * granted - granted)

    # Membership links: setting a flag to 1 must force the field into its list.
    cs.assert_zero(f_role * _membership_product(r, ROLE_OK))
    cs.assert_zero(f_clear * _membership_product(c, CLEARANCE_OK))
    # BUG (planted): the region membership link is missing.  f_region is only
    # constrained to be a bit — nothing forces region into REGION_OK.
    #   cs.assert_zero(f_region * _membership_product(g, REGION_OK))

    # granted is the AND of the three flags.
    cs.assert_zero(granted - f_role * f_clear * f_region)

    cs.set_output(granted)
    return granted


def honest_witness(role: int, clearance: int, region: int) -> dict[str, int]:
    """The assignment an honest prover would use for this credential."""
    return {
        "role": role,
        "clearance": clearance,
        "region": region,
        "f_role": 1 if role in ROLE_OK else 0,
        "f_clearance": 1 if clearance in CLEARANCE_OK else 0,
        "f_region": 1 if region in REGION_OK else 0,
        "granted": 1 if authorized(role, clearance, region) else 0,
    }
